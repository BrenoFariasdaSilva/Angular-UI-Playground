import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve } from 'node:path';
import { parseEnv } from 'node:util';

const root = resolve(import.meta.dirname, '..');
const envPath = resolve(root, '.env');
const outputPath = resolve(root, 'src/app/primeui-license.ts');
const localEnv = existsSync(envPath) ? parseEnv(readFileSync(envPath, 'utf8')) : {};
const license = process.env.PRIMEUI_LICENSE ?? localEnv.PRIMEUI_LICENSE;
const missing = !license?.trim() || license === 'YOUR_PRIMEUI_LICENSE_KEY';

if (missing && !process.argv.includes('--editor-placeholder')) {
  console.error('PrimeUI license is missing. Copy .env.example to .env and set PRIMEUI_LICENSE to your own key, or set PRIMEUI_LICENSE in the process environment.');
  process.exit(1);
}

if (!missing && /\s/.test(license)) {
  console.error('PRIMEUI_LICENSE contains whitespace. Check that the complete key was copied correctly.');
  process.exit(1);
}

const source = `// Generated by scripts/prepare-primeui-license.mjs; do not commit.\nexport const PRIMEUI_LICENSE = ${JSON.stringify(missing ? '' : license)};\n`;

if (!existsSync(outputPath) || readFileSync(outputPath, 'utf8') !== source) {
  writeFileSync(outputPath, source, { mode: 0o600 });
}

if (missing) {
  console.warn('PrimeUI license is not configured. Set PRIMEUI_LICENSE in .env or the process environment before starting or building the app.');
}
